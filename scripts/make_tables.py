def load(name: str) -> pd.DataFrame:
    return pd.read_parquet(RES / f"{name}.parquet")


def sidecar(name: str) -> dict:
    return json.loads((RES / f"{name}.json").read_text())


class Macros:
    def __init__(self):
        self.lines = ["% generated by scripts/make_tables.py\n"]

    def __call__(self, name: str, value):
        # a later definition of a macro replaces the earlier one
        assert re.fullmatch(r"[A-Za-z]+", name), name
        line = f"\\newcommand{{\\{name}}}{{{value}}}\n"
        prefix = f"\\newcommand{{\\{name}}}{{"
        for i, old in enumerate(self.lines):
            if old.startswith(prefix):
                self.lines[i] = line
                return
        self.lines.append(line)


def f(x, d=2):
    return f"{x:.{d}f}"


def p_text(p: float) -> str:
    if p is None or (isinstance(p, float) and np.isnan(p)):
        return "n/a"
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def date_text(ts) -> str:
    ts = pd.Timestamp(ts)
    return f"{ts.day} {ts.strftime('%B')} {ts.year}"


def write_table(name: str, lines: list[str]):
    (OUT / f"{name}.tex").write_text("% generated by scripts/make_tables.py\n" + "".join(lines), encoding="utf-8")


def add_short_context(refs, summary):
    """Append the runs of short_context_summary that are missing from the reference scores."""
    s = summary.rename(columns={"mean_width_80pct": "interval_width_k"}).copy()
    s.loc[~s["covariate"], "model"] = s.loc[~s["covariate"], "model"] + "_nocov"
    s["model"] = s["model"].replace({"timesfm3": "tsfm3", "timesfm3_nocov": "tsfm3_nocov"})
    have = set(zip(refs["model"], refs["context_steps"]))
    s = s[[(m, c) not in have for m, c in zip(s["model"], s["context_steps"])]]
    cols = ["model", "context_steps", "context_days", "crps", "coverage_80pct", "interval_width_k"]
    rows = [s[cols].assign(eval_set=e) for e in ("matched", "common")]
    return pd.concat([refs, *rows], ignore_index=True)

